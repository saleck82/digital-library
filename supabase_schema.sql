-- Starter schema for Supabase (PostgreSQL)
-- Run in Supabase Dashboard -> SQL Editor.
-- This schema stores metadata, not large media files.
create table if not exists public.library_items (
  id bigint generated by default as identity primary key,
  title_ar text not null,
  title_fr text,
  title_en text,
  description_ar text,
  description_fr text,
  description_en text,
  author text,
  media_type text not null check (media_type in ('book','audio','video','image')),
  language_code text not null default 'ar' check (language_code in ('ar','fr','en','multi')),
  media_url text,
  cover_url text,
  license_note text,
  is_published boolean not null default false,
  is_premium boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.library_items enable row level security;

-- Public can read published free items. Premium enforcement should be implemented
-- through a trusted backend / server-side checks, not a public client flag alone.
create policy "Public read published free items"
on public.library_items for select
using (is_published = true and is_premium = false);

